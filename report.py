# Turn a scan into (1) a self-contained HTML evidence report and (2) a message to send the vendor.
import base64
import html
import os

from receivers import pretty_site


def vendor_message(r):
    outside = [l for l in r["leaks"] if l.get("third_party")]
    if not outside:
        return ""
    done, rows = set(), []
    for l in outside:
        key = (l["host"], l.get("field", "email"))
        if key in done:
            continue
        done.add(key)
        rows.append(f"  - {l['company']} ({l['host']}) received the {l.get('field', 'email')} ({l['disguise']}), "
                    f"about {l['seconds_after_typing']}s after typing started")
    lines = "\n".join(rows)
    ident = r.get("identity") or {"email": r["canary"]}
    typed = ", ".join(f"{k} ({v})" for k, v in ident.items())
    cookie = ("\nThis happened after we clicked \"reject\" on your cookie banner.\n"
              if r.get("cookie_choice") == "rejected" else "")
    name = pretty_site(r['site'])
    return f"""Subject: Your {name} form shares what people type before they submit

Hi {name} team,

We're evaluating your platform for an event and ran a privacy check on {r['url']} on {r['time']}.

We typed test details into the form ({typed}) and did NOT submit it.
Before any submission, the page sent them to outside companies:
{lines}
{cookie}
Attendees reasonably expect nothing to happen until they click submit. Could you tell us:
  1. Why this information is shared before submission, and with whom?
  2. Whether this can be turned off for our event's pages?

The full evidence report (exact requests, timestamps and a screenshot) is attached.
You can verify the hashed values yourself by hashing the test values above.

Thanks,
[Your name]
"""


def evidence_html(r):
    e = html.escape
    outside = [l for l in r["leaks"] if l.get("third_party")]
    verdict = (f"<div class='bad'>The typed details were sent to {len({l['host'] for l in outside})} "
               f"outside compan{'y' if len({l['host'] for l in outside}) == 1 else 'ies'} before submit.</div>"
               if outside else "<div class='good'>No pre-submit leak to outside companies was observed.</div>")
    rows = "".join(f"""<tr><td><b>{e(l['company'])}</b><br><small>{e(l['category'])}</small></td>
        <td>{e(l.get('field', 'email'))}</td><td>{e(l['host'])}</td><td>{e(l['disguise'])}</td><td>{e(l['method'])}</td>
        <td>{l['seconds_after_typing']}s</td></tr>
        <tr><td colspan=6><code>{e(l['request_url'][:600])}</code></td></tr>""" for l in outside)
    steps = "".join(f"<li>{e(s)}</li>" for s in r.get("steps", []))
    img = ""
    if r.get("screenshot") and os.path.exists(r["screenshot"]):
        b64 = base64.b64encode(open(r["screenshot"], "rb").read()).decode()
        img = f"<h2>Screenshot at the end of the test</h2><img src='data:image/png;base64,{b64}'><p><small>Email typed. Submit never clicked.</small></p>"
    leak_table = (f"<h2>What left the page</h2><table><tr><th>Company</th><th>What</th><th>Server</th><th>Disguise</th>"
                  f"<th>Method</th><th>Timing</th></tr>{rows}</table>") if outside else ""
    return f"""<!doctype html><html><head><meta charset="utf-8"><title>Canary report: {e(r['site'])}</title>
<style>
body{{font-family:-apple-system,Segoe UI,sans-serif;max-width:860px;margin:32px auto;padding:0 16px;color:#222}}
.bad{{background:#fde8e8;border-left:5px solid #d33;padding:14px;font-size:1.15em}}
.good{{background:#e7f6ea;border-left:5px solid #2a8;padding:14px;font-size:1.15em}}
table{{border-collapse:collapse;width:100%}} td,th{{border:1px solid #ddd;padding:8px;text-align:left;vertical-align:top}}
code{{word-break:break-all;font-size:.8em;color:#555}} img{{max-width:100%;border:1px solid #ccc}}
.meta td{{border:none;padding:2px 12px 2px 0}}
</style></head><body>
<h1>Canary evidence report</h1>
<table class="meta">
<tr><td>Page tested</td><td><b>{e(r['url'])}</b></td></tr>
<tr><td>When</td><td>{e(r['time'])}</td></tr>
<tr><td>Fake details used</td><td><code>{e(', '.join((r.get('identity') or {'email': r['canary']}).values()))}</code> (exist nowhere else)</td></tr>
<tr><td>Cookie banner</td><td>{'Rejected' if r.get('cookie_choice') == 'rejected' else 'Not clicked'}</td></tr>
<tr><td>Form submitted?</td><td><b>Never</b></td></tr>
</table>
{verdict}
<h2>What the test did</h2><ol>{steps}</ol>
{leak_table}
<h2>How to verify this yourself</h2>
<p>Hashes look random, but the same email always produces the same hash. Compute the SHA-256 / MD5 / SHA-1
of <code>{e(r['canary'])}</code> (for example with <code>echo -n "{e(r['canary'])}" | shasum -a 256</code>)
and compare it with the values in the requests above.</p>
{img}
<p><small>Generated by Canary. This report describes network behaviour observed during one automated test.
It is not a legal finding.</small></p>
</body></html>"""
